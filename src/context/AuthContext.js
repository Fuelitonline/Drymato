const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;
const NAME_RE = /^[\p{L}][\p{L}\p{M} .'-]*$/u;

export function normalizeMobile(value = "") {
    let d = String(value).replace(/[^\d+]/g, "");
    if (d.startsWith("+91")) d = d.slice(3);
    else if (d.startsWith("91") && d.length === 12) d = d.slice(2);
    else if (d.startsWith("0") && d.length === 11) d = d.slice(1);
    return d.replace(/\D/g, "");
}

export function splitName(name = "") {
    const parts = String(name).trim().split(/\s+/).filter(Boolean);
    return { firstName: parts[0] || "", lastName: parts.slice(1).join(" ") };
}

const checkPassword = (v = "", emptyMessage) => {
    if (!v) return emptyMessage;
    if (v.length < 8) return "Use at least 8 characters.";
    if (v.length > 64) return "Use 64 characters or fewer.";
    if (!/[A-Za-z]/.test(v) || !/\d/.test(v)) return "Include at least one letter and one number.";
    return "";
};

export const validators = {
    name: (v = "") => {
        const s = v.trim().replace(/\s+/g, " ");
        if (!s) return "Enter your name.";
        if (s.length > 60) return "Name must be 60 characters or fewer.";
        if (!NAME_RE.test(s)) return "Name can only contain letters, spaces and . ' -";
        if (REQUIRE_LAST_NAME && s.split(" ").length < 2) return "Enter your first and last name.";
        if (s.length < 2) return "Name must be at least 2 characters.";
        return "";
    },
    email: (v = "") => {
        const s = v.trim();
        if (!s) return "Enter your email address.";
        if (s.length > 254 || !EMAIL_RE.test(s)) return "Enter a valid email address.";
        return "";
    },
    mobile: (v = "") => {
        if (!v.trim()) return "Enter your mobile number.";
        if (!/^[6-9]\d{9}$/.test(normalizeMobile(v))) return "Enter a valid 10-digit mobile number.";
        return "";
    },
    password: (v = "") => checkPassword(v, "Create a password."),
    newPassword: (v = "") => checkPassword(v, "Enter a new password."),
    loginPassword: (v = "") => (v ? "" : "Enter your password."),
    otp: (v = "") => (new RegExp(`^\\d{${OTP_LENGTH}}$`).test(v) ? "" : `Enter the ${OTP_LENGTH}-digit code.`),
};

