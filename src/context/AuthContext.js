const AuthContext = createContext(null);
const MODAL_VIEWS = ["login", "signup", "forgot"];

export function AuthProvider({ children }) {
    const [user, setUser] = useState(null);
    const [status, setStatus] = useState("loading");
    const [isModalOpen, setIsModalOpen] = useState(false);
    const [modalView, setModalView] = useState("login");

    const clearSession = useCallback(() => {
        if (typeof window !== "undefined") {
            localStorage.removeItem("drymato_token");
        }
        setUser(null);
        setStatus("unauthenticated");
    }, []);

    // const refreshSession = useCallback(async () => {
    //     if (!API_BASE) {
    //         clearSession();
    //         return null;
    //     }
    //     try {
    //         const profile = await fetchProfile();
    //         setUser(profile);
    //         setStatus(profile ? "authenticated" : "unauthenticated");
    //         return profile;
    //     } catch (err) {
    //         if (err?.status === 401 || err?.status === 403) clearSession();
    //         else setStatus((prev) => (prev === "loading" ? "unauthenticated" : prev));
    //         return null;
    //     }
    // }, [clearSession]);

    const refreshSession = useCallback(async () => {
        if (!API_BASE) {
            clearSession();
            return null;
        }

        // Optional: If using localStorage tokens, don't ping profile if no token exists
        if (typeof window !== "undefined" && !localStorage.getItem("drymato_token")) {
            clearSession();
            return null;
        }

        try {
            const profile = await fetchProfile();
            setUser(profile);
            setStatus(profile ? "authenticated" : "unauthenticated");
            return profile;
        } catch (err) {
            if (err?.status === 401 || err?.status === 403) clearSession();
            else setStatus((prev) => (prev === "loading" ? "unauthenticated" : prev));
            return null;
        }
    }, [clearSession]);

    useEffect(() => {
        refreshSession();
    }, [refreshSession]);

    useEffect(() => {
        const onStorage = (e) => {
            if (e.key === SYNC_KEY) refreshSession();
        };
        window.addEventListener("storage", onStorage);
        return () => window.removeEventListener("storage", onStorage);
    }, [refreshSession]);

    useEffect(() => {
        sessionExpiredHandler = () => {
            clearSession();
            toast.error(SESSION_EXPIRED_MESSAGE);
            setModalView("login");
            setIsModalOpen(true);
        };
        return () => {
            sessionExpiredHandler = null;
        };
    }, [clearSession]);

    useEffect(() => {
        const params = new URLSearchParams(window.location.search);
        const view = params.get("auth");
        if (!MODAL_VIEWS.includes(view)) return;

        setModalView(view);
        setIsModalOpen(true);

        params.delete("auth");
        const qs = params.toString();
        window.history.replaceState(
            null,
            "",
            window.location.pathname + (qs ? `?${qs}` : "") + window.location.hash
        );
    }, []);

    const openAuthModal = useCallback((view = "login") => {
        setModalView(MODAL_VIEWS.includes(view) ? view : "login");
        setIsModalOpen(true);
    }, []);
    const closeAuthModal = useCallback(() => setIsModalOpen(false), []);

    const establishSession = useCallback(async (responseData) => {
        // Capture and store token in localStorage if present in response
        const token = extractToken(responseData);
        if (token && typeof window !== "undefined") {
            localStorage.setItem("drymato_token", token);
        }

        const fromResponse = normalizeUser(pickUserObject(responseData));

        let profile = null;
        try {
            profile = await fetchProfile();
        } catch (err) {
            if (err?.status === 401 || err?.status === 403) {
                // If token was stored or returned, try one more time or fallback
            }
        }

        const next = profile || fromResponse;
        if (!next) {
            throw new AuthError("Unexpected response from the server. Please try again.", { code: "BAD_RESPONSE" });
        }

        setUser(next);
        setStatus("authenticated");
        broadcast("login");
        return next;
    }, []);

    const login = useCallback(
        async ({ email, password }) => {
            const data = await request(AUTH_ENDPOINTS.login, { method: "POST", body: { email, password } });
            return establishSession(data);
        },
        [establishSession]
    );

    const signup = useCallback(
        async ({ name, email, mobile, password }) => {
            const { firstName, lastName } = splitName(name);
            const created = await request(AUTH_ENDPOINTS.signup, {
                method: "POST",
                body: {
                    firstName,
                    lastName,
                    email,
                    mobileNumber: mobile,
                    password,
                    confirmPassword: password,
                    agreeToTerms: true,
                    domainName: STORE_NAME,
                },
            });

            let loginData;
            try {
                loginData = await request(AUTH_ENDPOINTS.login, { method: "POST", body: { email, password } });
            } catch {
                return {
                    user: null,
                    loginRequired: true,
                    message: readMessage(created) || "Account created. Please log in.",
                };
            }

            return { user: await establishSession(loginData), loginRequired: false };
        },
        [establishSession]
    );

    const googleLogin = useCallback(
        async (credential) => {
            if (!credential) throw new AuthError("Google sign-in failed. Please try again.");
            const data = await request(AUTH_ENDPOINTS.google, {
                method: "POST",
                body: { [GOOGLE_TOKEN_FIELD]: credential, domainName: STORE_NAME },
                fallbacks: { 401: "Google sign-in failed. Please try again." },
            });
            return establishSession(data);
        },
        [establishSession]
    );

    const logout = useCallback(async () => {
        try {
            await request(AUTH_ENDPOINTS.logout, { method: "POST", authed: true });
        } catch {
            /* ignore server error on logout */
        }
        clearSession();
        broadcast("logout");
        toast.success("You have been logged out.");
        return true;
    }, [clearSession]);

    const updateProfile = useCallback(
        async (fields) => {
            if (!user?.id) throw new AuthError(SESSION_EXPIRED_MESSAGE, { status: 401 });

            let body = fields;
            if (!(typeof FormData !== "undefined" && fields instanceof FormData)) {
                body = {};
                if (fields.name !== undefined) Object.assign(body, splitName(fields.name));
                if (fields.email !== undefined) body.email = fields.email;
                if (fields.mobile !== undefined) body.mobileNumber = normalizeMobile(fields.mobile);
                if (fields.gender !== undefined) body.gender = fields.gender;
            }

            const data = await request(AUTH_ENDPOINTS.updateProfile(user.id), {
                method: "PUT",
                body,
                authed: true,
            });
            const fresh = await fetchProfile().catch(() => null);
            if (fresh) setUser(fresh);
            return readMessage(data) || "Profile updated.";
        },
        [user]
    );

    const changePassword = useCallback(async ({ currentPassword, newPassword }) => {
        const data = await request(AUTH_ENDPOINTS.changePassword, {
            method: "PUT",
            body: { currentPassword, newPassword },
            authed: true,
            fallbacks: { 400: "Please check your current and new password." },
        });
        return readMessage(data) || "Password updated.";
    }, []);

    const deleteAccount = useCallback(async () => {
        if (!user?.id) throw new AuthError(SESSION_EXPIRED_MESSAGE, { status: 401 });
        const data = await request(AUTH_ENDPOINTS.deleteUser(user.id), { method: "DELETE", authed: true });
        clearSession();
        broadcast("logout");
        return readMessage(data) || "Your account has been deleted.";
    }, [user, clearSession]);

    const forgotPassword = useCallback(async (email) => {
        const data = await request(AUTH_ENDPOINTS.forgotPassword, { method: "POST", body: { email } });
        return readMessage(data);
    }, []);

    const resetPassword = useCallback(async ({ email, otp, newPassword }) => {
        const data = await request(AUTH_ENDPOINTS.verifyOtp, {
            method: "POST",
            body: { email, otp, newPassword },
            fallbacks: { 400: "That code is invalid or has expired." },
        });
        return readMessage(data) || "Password updated.";
    }, []);

    const value = useMemo(
        () => ({
            user,
            status,
            isAuthenticated: status === "authenticated",
            isModalOpen,
            modalView,
            setModalView,
            openAuthModal,
            closeAuthModal,
            refreshSession,
            login,
            signup,
            googleLogin,
            logout,
            updateProfile,
            changePassword,
            deleteAccount,
            forgotPassword,
            resetPassword,
        }),
        [
            user,
            status,
            isModalOpen,
            modalView,
            openAuthModal,
            closeAuthModal,
            refreshSession,
            login,
            signup,
            googleLogin,
            logout,
            updateProfile,
            changePassword,
            deleteAccount,
            forgotPassword,
            resetPassword,
        ]
    );

    return <AuthContext.Provider value={value}>{children}</AuthContext.Provider>;
}

export function useAuth() {
    const ctx = useContext(AuthContext);
    if (!ctx) throw new Error("useAuth must be used inside <AuthProvider>");
    return ctx;
}