export class AuthError extends Error {
    constructor(message, { status = 0, code = "", fieldErrors = null } = {}) {
        super(message);
        this.name = "AuthError";
        this.status = status;
        this.code = code;
        this.fieldErrors = fieldErrors;
    }
}

const DEFAULT_MESSAGES = {
    400: "Please check the details you entered.",
    401: "Incorrect email or password.",
    403: "This account is not allowed to sign in.",
    404: "We could not find an account with those details.",
    409: "An account with this email already exists.",
    422: "Please check the details you entered.",
    429: "Too many attempts. Please wait a moment and try again.",
};

const REQUEST_TIMEOUT_MS = 20000;
let sessionExpiredHandler = null;

export async function apiRequest(path, { method = "GET", body, fallbacks = {}, authed = false } = {}) {
    if (!API_BASE) {
        throw new AuthError("This feature is not available right now. Please try again later.", {
            code: "NOT_CONFIGURED",
        });
    }

    const isForm = typeof FormData !== "undefined" && body instanceof FormData;
    const headers = { Accept: "application/json" };
    if (body && !isForm) headers["Content-Type"] = "application/json";

    // Attach token from localStorage if available
    if (typeof window !== "undefined") {
        const token = localStorage.getItem("drymato_token");
        if (token) {
            headers["Authorization"] = `Bearer ${token}`;
        }
    }

    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);

    let res;
    try {
        res = await fetch(`${API_BASE}${path}`, {
            method,
            credentials: "include",
            cache: "no-store",
            headers,
            body: body ? (isForm ? body : JSON.stringify(body)) : undefined,
            signal: controller.signal,
        });
    } catch (err) {
        throw new AuthError(
            err?.name === "AbortError"
                ? "The request took too long. Please try again."
                : "Network error. Check your connection and try again.",
            { code: err?.name === "AbortError" ? "TIMEOUT" : "NETWORK" }
        );
    } finally {
        clearTimeout(timer);
    }

    let data = null;
    try {
        data = await res.json();
    } catch {
        /* empty or non-JSON body */
    }

    if (!res.ok || data?.success === false) {
        const status = res.ok ? 400 : res.status;
        const expired = authed && status === 401;
        if (expired) sessionExpiredHandler?.();

        const message = expired
            ? SESSION_EXPIRED_MESSAGE
            : readMessage(data) ||
            fallbacks[status] ||
            DEFAULT_MESSAGES[status] ||
            (status >= 500
                ? "Something went wrong on our side. Please try again shortly."
                : "Something went wrong. Please try again.");

        throw new AuthError(message, {
            status,
            code: typeof data?.code === "string" ? data.code : "",
            fieldErrors: readFieldErrors(data),
        });
    }

    return data;
}

const request = apiRequest;

async function fetchProfile() {
    // return normalizeUser(pickUserObject(await request(AUTH_ENDPOINTS.profile, { authed: true })));
    // DO NOT pass { authed: true } here so 401 isn't treated as a session expiry
    return normalizeUser(pickUserObject(await request(AUTH_ENDPOINTS.profile)));
}

