const FIELD_MAP = {
    firstName: "name",
    lastName: "name",
    mobileNumber: "mobile",
    confirmPassword: "password",
    newPassword: "password",
};

function readMessage(data) {
    if (typeof data?.message === "string" && data.message) return data.message;
    if (typeof data?.error === "string" && data.error) return data.error;
    return "";
}

function readFieldErrors(data) {
    const source = data?.errors ?? data?.data?.errors;
    if (!source || typeof source !== "object") return null;

    const out = {};
    const add = (key, message) => {
        if (typeof key !== "string" || typeof message !== "string" || !message) return;
        const field = FIELD_MAP[key] || key;
        if (!out[field]) out[field] = message;
    };

    if (Array.isArray(source)) {
        source.forEach((item) => add(item?.field ?? item?.path ?? item?.param, item?.message ?? item?.msg));
    } else {
        Object.entries(source).forEach(([key, value]) => add(key, value));
    }
    return Object.keys(out).length ? out : null;
}

function pickUserObject(payload) {
    const candidates = [payload?.data?.user, payload?.data?.customer, payload?.user, payload?.data, payload];
    return (
        candidates.find(
            (c) => c && typeof c === "object" && !Array.isArray(c) && (c.email || c._id || c.id)
        ) || null
    );
}

// Extracts token from various possible keys in backend response
function extractToken(payload) {
    return (
        payload?.token ||
        payload?.data?.token ||
        payload?.accessToken ||
        payload?.data?.accessToken ||
        null
    );
}

export function normalizeUser(raw) {
    if (!raw) return null;
    const firstName = raw.firstName || "";
    const lastName = raw.lastName || "";
    const image = raw.profileImage ?? raw.avatar ?? raw.picture ?? "";
    return {
        id: raw._id || raw.id || raw.userId || "",
        name:
            [firstName, lastName].filter(Boolean).join(" ").trim() ||
            raw.name ||
            raw.fullName ||
            String(raw.email || "").split("@")[0],
        firstName,
        lastName,
        email: raw.email || "",
        mobile: raw.mobileNumber || raw.mobile || "",
        gender: raw.gender || "",
        avatar: typeof image === "string" ? image : image?.url || "",
        role: raw.role || "user",
    };
}

